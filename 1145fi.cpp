void ray() {freopen("i.inp", "r", stdin); freopen("o.out", "w", stdout);}

int mod = 1000000007;
const int maxn = 2e5+10;

int BIT[maxn], n;

int query(int i){
    int maxx = 0;
    for (; i > 0; i -= (i & -i)){
        maxx = max(maxx, BIT[i]);
    }

    return maxx;
}

void update(int i, int val){
    for (; i <= n; i += (i & -i)){
        BIT[i] = max(BIT[i], val);
    }
}

signed main() {
    ios_base::sync_with_stdio(false);
    cin.tie(nullptr);

    #ifndef ONLINE_JUDGE
        ray();
    #endif

    cin >> n;
    vector<int> a(n);
    for (int i = 0; i < n; ++i) cin >> a[i];

    vector<int> b = a;
    sort(b.begin(), b.end());
    b.erase(unique(b.begin(), b.end()), b.end());

    for (int i = 0; i < n; ++i){
        int f = lower_bound(b.begin(), b.end(), a[i]) - b.begin();
        a[i] = f+1;
    }

    memset(BIT, 0, sizeof(BIT));
    
    for (int i = 0; i < n; ++i){
        int cow = query(a[i]-1);

        update(a[i], cow+1);
    }

    int ans = 0;
    for (int i = 1; i <= n; ++i){
        ans = max(ans, BIT[i]);
    }

    cout << ans;
    return 0;
}